import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {project,createSkyFrame,observerZenith} from '../src/game.js';
import {angularOutline} from '../src/deep-sky.js';

const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||undefined});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://gc.zgo.at/**',route=>route.abort());
  await page.route('https://mmilanta.goatcounter.com/**',route=>route.abort());
 await page.route('https://skyview.gsfc.nasa.gov/**',route=>route.abort());
  let requests=[];
  await page.route('**/hips-image-services/hips2fits?**',route=>{
    requests.push(new URL(route.request().url()));
    return route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512"><rect width="512" height="512" fill="#152333"/></svg>'});
  });
  await page.addInitScript(()=>{
    const clear=CanvasRenderingContext2D.prototype.clearRect,draw=CanvasRenderingContext2D.prototype.drawImage;
    window.skyImageSources=[];
    CanvasRenderingContext2D.prototype.clearRect=function(...args){if(this.canvas.id==='sky')window.skyImageSources=[];return clear.apply(this,args);};
    CanvasRenderingContext2D.prototype.drawImage=function(source,...args){if(this.canvas.id==='sky')window.skyImageSources.push(source instanceof HTMLImageElement?'image':'canvas');return draw.call(this,source,...args);};
    localStorage.setItem('starhopper.observer',JSON.stringify({latitude:41,month:11}));
    if (!localStorage.getItem('starhopper.discovered')) localStorage.setItem('starhopper.discovered',JSON.stringify(['Vega']));
  });
  await page.goto(process.env.TEST_URL||'http://localhost:5173');
  await page.waitForSelector('#loading',{state:'detached'});
  const objects=JSON.parse(fs.readFileSync('public/data/deep-sky.json'));
  const andromeda=objects.find(o=>o.id==='NGC0224');
  const box=await page.locator('#sky').boundingBox();
  const local=createSkyFrame(observerZenith(41,11)).toLocal(andromeda.ra,andromeda.dec);
  const point=project(local.ra,local.dec,{ra:0,dec:90,fov:76},box.width,box.height);
  await page.mouse.click(box.x+point[0],box.y+point[1]);
  assert.equal(await page.locator('#guess').getAttribute('placeholder'),'Galaxy');
  assert.equal(await page.locator('#star-kind').textContent(),'');
  assert.ok(await page.locator('.panel-heading').isHidden());
  await page.locator('#guess').fill('M31');await page.locator('#guess-form .submit').click();
  assert.equal(await page.locator('#score').textContent(),'2');
  assert.equal(await page.locator('#star-kind').textContent(),'Andromeda Galaxy');
  await page.reload();await page.waitForSelector('#loading',{state:'detached'});
  assert.equal(await page.locator('#score').textContent(),'2');
  await page.locator('#done').click();
  await page.locator('#result-type').selectOption('galaxy');
  assert.equal(await page.locator('.result:visible').count(),objects.filter(o=>o.type==='galaxy').length);
  await page.locator('#result-search').fill('M31');
  assert.equal(await page.locator('.result:visible').count(),1);
  await page.locator('.result[data-star="NGC0224"]').click();
  await page.waitForFunction(()=>document.querySelector('#photo-credit').textContent==='DSS2 · STScI / CDS');
  assert.deepEqual(await page.evaluate(()=>window.skyImageSources),['image'],'a loaded survey replaces the panorama rather than blending duplicate star positions');
  assert.ok(requests.length>0);
  const wcs=JSON.parse(requests.at(-1).searchParams.get('wcs'));
  assert.ok(Math.abs(wcs.CRVAL1-andromeda.ra)<1e-8);
  assert.ok(Math.abs(wcs.CRVAL2-andromeda.dec)<1e-8);
  // Click the galaxy's body, well outside the old 18px central hit target.
  await page.locator('#done').click();
  const frame=createSkyFrame(observerZenith(41,11));
  const [ra,dec]=angularOutline(andromeda)[0][0],edge=frame.toLocal(ra,dec);
  const edgePoint=project(edge.ra,edge.dec,{...local,fov:andromeda.majorArcmin/60*3},box.width,box.height);
  const x=box.width/2+(edgePoint[0]-box.width/2)*.7,y=box.height/2+(edgePoint[1]-box.height/2)*.7;
  assert.ok(Math.hypot(x-box.width/2,y-box.height/2)>18);
  await page.mouse.click(box.x+x,box.y+y);
  assert.equal(await page.locator('#star-kind').textContent(),'Andromeda Galaxy');
  await page.locator('#done').click();
  await page.locator('#survey').click();assert.equal(await page.locator('#survey').getAttribute('aria-pressed'),'false');
  await page.unroute('**/hips-image-services/hips2fits?**');
  await page.route('**/hips-image-services/hips2fits?**',route=>route.abort());
  await page.unroute('https://skyview.gsfc.nasa.gov/**');
  await page.route('https://skyview.gsfc.nasa.gov/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512"><rect width="512" height="512" fill="#1b2832"/></svg>'}));
  await page.locator('#survey').click();
  await page.locator('#sky').focus();await page.keyboard.press('+');
  await page.waitForFunction(()=>document.querySelector('#photo-credit').textContent==='DSS2 · STScI / NASA SkyView');
  assert.deepEqual(await page.evaluate(()=>window.skyImageSources),['image']);
  await page.unroute('https://skyview.gsfc.nasa.gov/**');
  await page.route('https://skyview.gsfc.nasa.gov/**',route=>route.abort());
  await page.keyboard.press('+');
  await page.waitForFunction(()=>document.querySelector('#photo-credit').textContent.includes('Survey unavailable'));
  assert.equal(await page.locator('#score').textContent(),'2');
  await page.locator('#result-search').fill('');await page.locator('#result-type').selectOption('nebula');
  assert.equal(await page.locator('.result:visible').count(),objects.filter(o=>o.type==='nebula').length);
  await page.locator('.result[data-star="NGC1976"]').click();
  assert.match(await page.locator('#star-detail').textContent(),/Nebula/);
  await page.screenshot({path:'/tmp/starhopper-deep-sky-desktop.png'});
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.ok(await page.locator('#survey').isVisible());
    await page.screenshot({path:`/tmp/starhopper-deep-sky-mobile-${width}.png`});
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#result-type').selectOption('cluster');
  assert.equal(await page.locator('.result:visible').count(),26);
  await page.locator('#result-search').fill('M13');
  assert.equal(await page.locator('.result:visible').count(),1);
  await page.locator('.result[data-star="NGC6205"]').click();
  assert.match(await page.locator('#star-detail').textContent(),/Globular cluster/);
  await page.locator('#done').click();
  let sky=await page.locator('#sky').boundingBox();
  await page.mouse.click(sky.x+sky.width/2,sky.y+sky.height/2);
  assert.equal(await page.locator('#guess').getAttribute('placeholder'),'Globular cluster');
  assert.equal(await page.locator('#star-kind').textContent(),'');
  assert.ok(await page.locator('.panel-heading').isHidden());
  await page.locator('#guess').fill('M13');await page.locator('#guess-form .submit').click();
  assert.equal(await page.locator('#score').textContent(),'3');
  await page.reload();await page.waitForSelector('#loading',{state:'detached'});
  assert.equal(await page.locator('#score').textContent(),'3');
  await page.locator('#done').click();await page.locator('#result-type').selectOption('cluster');
  await page.locator('#result-search').fill('Seven Sisters');
  assert.equal(await page.locator('.result:visible').count(),1);
  await page.locator('.result[data-star="Mel022"]').click();
  assert.match(await page.locator('#star-detail').textContent(),/Open cluster/);
  await page.screenshot({path:'/tmp/starhopper-pleiades-cluster.png'});
  await page.locator('#done').click();
  sky=await page.locator('#sky').boundingBox();
  await page.mouse.click(sky.x+sky.width/2,sky.y+sky.height/2);
  assert.equal(await page.locator('#guess').getAttribute('placeholder'),'Open cluster');
  assert.equal(await page.locator('#star-kind').textContent(),'');
  assert.ok(await page.locator('.panel-heading').isHidden());
  await page.locator('#guess').fill('M45');await page.locator('#guess-form .submit').click();
  assert.equal(await page.locator('#score').textContent(),'4');
  assert.deepEqual(errors,[]);
  console.log('Deep-sky browser checks passed: selection, M31 scoring, persistence, type filters, survey WCS, HD toggle, unavailable survey, mobile.');
} finally {await browser.close();}
